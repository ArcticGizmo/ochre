using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using Ochre.Host.Bridge;

// Writes ui/src/generated/bridge-types.ts from BridgeContract (ADR 0009).
// Usage: dotnet run --project tools/Ochre.BridgeGen [-- --check]

var check = args.Contains("--check");
var root = FindRepoRoot(Environment.CurrentDirectory) ?? FindRepoRoot(AppContext.BaseDirectory)
    ?? throw new InvalidOperationException("run from inside the Ochre repo");
var output = Path.Combine(root, "ui", "src", "generated", "bridge-types.ts");

var generated = new TsGenerator().Generate();
var existing = File.Exists(output) ? File.ReadAllText(output).Replace("\r\n", "\n", StringComparison.Ordinal) : null;

if (check)
{
    if (existing == generated)
    {
        Console.WriteLine("bridge-types.ts is up to date");
        return 0;
    }
    Console.Error.WriteLine("bridge-types.ts is stale; run: dotnet run --project tools/Ochre.BridgeGen");
    return 1;
}

Directory.CreateDirectory(Path.GetDirectoryName(output)!);
if (existing != generated) File.WriteAllText(output, generated, new UTF8Encoding(false));
Console.WriteLine(existing == generated ? "bridge-types.ts unchanged" : $"wrote {Path.GetRelativePath(root, output)}");
return 0;

static string? FindRepoRoot(string start)
{
    for (var dir = new DirectoryInfo(start); dir is not null; dir = dir.Parent)
        if (File.Exists(Path.Combine(dir.FullName, "Ochre.slnx"))) return dir.FullName;
    return null;
}

internal sealed class TsGenerator
{
    private readonly NullabilityInfoContext _nullability = new();
    private readonly List<Type> _records = [];
    private readonly List<Type> _enums = [];

    public string Generate()
    {
        foreach (var r in BridgeContract.Requests)
        {
            Discover(r.Request);
            Discover(r.Response);
        }
        foreach (var e in BridgeContract.Events) Discover(e.Payload);

        var sb = new StringBuilder();
        sb.Append("// Generated by tools/Ochre.BridgeGen from src/Ochre.Host/Bridge/BridgeContract.cs. Do not edit.\n");
        sb.Append("// Regenerate: dotnet run --project tools/Ochre.BridgeGen\n\n");

        foreach (var e in _enums.OrderBy(t => t.Name, StringComparer.Ordinal))
            sb.Append($"export type {e.Name} = {string.Join(" | ", EnumValues(e).Select(v => $"'{v}'"))};\n\n");

        foreach (var r in _records.OrderBy(t => t.Name, StringComparer.Ordinal))
        {
            var props = Properties(r);
            if (props.Count == 0)
            {
                sb.Append($"export type {r.Name} = Record<string, never>;\n\n");
                continue;
            }
            sb.Append($"export interface {r.Name} {{\n");
            foreach (var p in props)
                sb.Append($"  {JsonNamingPolicy.CamelCase.ConvertName(p.Name)}: {TsType(p.PropertyType, IsNullable(p))};\n");
            sb.Append("}\n\n");
        }

        sb.Append("export interface Requests {\n");
        foreach (var r in BridgeContract.Requests)
            sb.Append($"  '{r.Type}': {{ req: {TsType(r.Request, false)}; res: {TsType(r.Response, false)} }};\n");
        sb.Append("}\n\n");

        sb.Append("export interface Events {\n");
        foreach (var e in BridgeContract.Events)
            sb.Append($"  '{e.Name}': {TsType(e.Payload, false)};\n");
        sb.Append("}\n");
        return sb.ToString();
    }

    private void Discover(Type type)
    {
        type = Nullable.GetUnderlyingType(type) ?? type;
        if (ElementType(type) is { } element)
        {
            Discover(element);
            return;
        }
        if (type.IsEnum)
        {
            if (!_enums.Contains(type)) _enums.Add(type);
            return;
        }
        if (IsPrimitive(type) || _records.Contains(type)) return;
        if (!type.IsClass || type.Namespace != typeof(BridgeContract).Namespace)
            throw new NotSupportedException($"{type.FullName} can't cross the bridge; use a record in {typeof(BridgeContract).Namespace}");
        _records.Add(type);
        foreach (var p in Properties(type)) Discover(p.PropertyType);
    }

    private string TsType(Type type, bool nullable)
    {
        var underlying = Nullable.GetUnderlyingType(type);
        if (underlying is not null)
        {
            type = underlying;
            nullable = true;
        }
        var ts = ElementType(type) is { } element ? Wrap(TsType(element, false)) + "[]" : Name(type);
        return nullable ? ts + " | null" : ts;

        static string Wrap(string t) => t.Contains(' ', StringComparison.Ordinal) ? $"({t})" : t;
    }

    private static string Name(Type type) => type switch
    {
        _ when type == typeof(string) || type == typeof(Guid) || type == typeof(DateTimeOffset) || type == typeof(DateTime) => "string",
        _ when type == typeof(bool) => "boolean",
        _ when type == typeof(int) || type == typeof(long) || type == typeof(double) || type == typeof(float) || type == typeof(decimal) => "number",
        _ => type.Name,
    };

    private static bool IsPrimitive(Type type) => Name(type) != type.Name || type == typeof(string);

    private static Type? ElementType(Type type)
    {
        if (type.IsArray) return type.GetElementType();
        if (!type.IsGenericType) return null;
        var def = type.GetGenericTypeDefinition();
        return def == typeof(IReadOnlyList<>) || def == typeof(List<>) || def == typeof(IList<>) || def == typeof(IEnumerable<>)
            ? type.GetGenericArguments()[0]
            : null;
    }

    private static List<PropertyInfo> Properties(Type type) =>
        type.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
            .Where(p => p.GetMethod is { IsPublic: true } && p.GetIndexParameters().Length == 0)
            .OrderBy(p => p.MetadataToken)
            .ToList();

    private bool IsNullable(PropertyInfo p) =>
        Nullable.GetUnderlyingType(p.PropertyType) is not null || _nullability.Create(p).ReadState == NullabilityState.Nullable;

    private static IEnumerable<string> EnumValues(Type type) =>
        type.GetFields(BindingFlags.Public | BindingFlags.Static)
            .OrderBy(f => f.MetadataToken)
            .Select(f => f.GetCustomAttribute<JsonStringEnumMemberNameAttribute>()?.Name ?? JsonNamingPolicy.CamelCase.ConvertName(f.Name));
}
